// Generate worker/price-data.mjs from the models.dev price database.
//
//   node tools/generate-prices.mjs                       # fetch models.dev live
//   node tools/generate-prices.mjs --input dump.json     # offline / reproducible
//   node tools/generate-prices.mjs --out some/file.mjs
//
// The emitted file is data only: USD per 1M tokens, with the extra cache and
// long-context fields we price with. This script is a build tool and is never
// imported by the gateway at runtime.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { CATALOG_PROVIDERS } from '../worker/price-providers.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const DEFAULT_OUT = join(HERE, '..', 'worker', 'price-data.mjs')
const DEFAULT_URL = 'https://models.dev/api.json'
const FETCH_TIMEOUT_MS = 180_000

// Stable DeepSeek API aliases are listed by models.dev under third-party
// providers but carry a canonical `deepseek/...` id. Re-label them so agents
// using `deepseek-chat` / `deepseek-reasoner` get a real listed price.
const RELABELED = Object.freeze([
  { from: 'nano-gpt', id: 'deepseek-chat', provider: 'deepseek' },
  { from: 'helicone', id: 'deepseek-reasoner', provider: 'deepseek' }
])

const COST_FIELDS = {
  input: 'input',
  output: 'output',
  cacheRead: 'cache_read',
  cacheWrite: 'cache_write',
  reasoning: 'reasoning'
}

const finite = (value) => typeof value === 'number' && Number.isFinite(value) && value >= 0

function ratesFrom(cost) {
  const rates = {}
  for (const [field, source] of Object.entries(COST_FIELDS)) {
    if (finite(cost[source])) rates[field] = cost[source]
  }
  return rates
}

function tiersFrom(cost) {
  if (!Array.isArray(cost.tiers)) return []
  const tiers = []
  for (const tier of cost.tiers) {
    const size = tier?.tier?.size
    if (!finite(size)) continue
    const rates = ratesFrom(tier)
    // Cache rates can be absent; only input/output are required for a tier to
    // be usable. Reasoning is priced on the base entry when not listed.
    if (!finite(rates.input) || !finite(rates.output)) continue
    tiers.push({ size, ...rates })
  }
  return tiers.sort((a, b) => a.size - b.size)
}

function entryFrom(provider, id, model) {
  const cost = model?.cost
  if (!cost || typeof cost !== 'object') return null
  const rates = ratesFrom(cost)
  if (!finite(rates.input) || !finite(rates.output)) return null
  const entry = { id, provider, ...rates }
  const tiers = tiersFrom(cost)
  if (tiers.length) entry.tiers = tiers
  return entry
}

/**
 * Pure: turn a parsed models.dev api.json into the compact bundled catalog.
 * `asOf` is injected so tests are deterministic.
 */
export function buildCatalogData(json, { providers = CATALOG_PROVIDERS, asOf } = {}) {
  const ids = providers instanceof Set ? providers : new Set(providers)
  const byId = new Map()
  const add = (provider, id, model) => {
    const entry = entryFrom(provider, id, model)
    if (!entry) return
    byId.set(`${provider}/${id}`, entry)
  }
  for (const provider of ids) {
    for (const [id, model] of Object.entries(json?.[provider]?.models ?? {})) add(provider, id, model)
  }
  for (const { from, id, provider } of RELABELED) add(provider, id, json?.[from]?.models?.[id])
  const entries = [...byId.values()].sort((a, b) => {
    if (a.provider !== b.provider) return a.provider < b.provider ? -1 : 1
    return a.id < b.id ? -1 : a.id > b.id ? 1 : 0
  })
  const date = typeof asOf === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(asOf)
    ? asOf
    : new Date().toISOString().slice(0, 10)
  return { generatedAt: date, entries }
}

/** Render the generated ES module. Pure. */
export function renderCatalogModule({ generatedAt, entries }) {
  const body = JSON.stringify(entries, null, 2)
  return `// Generated by tools/generate-prices.mjs from https://models.dev/api.json on ${generatedAt}.
// Do not edit by hand. USD per 1M tokens. Re-run with: node tools/generate-prices.mjs
export const GENERATED_AT = ${JSON.stringify(generatedAt)}
export const PRICE_ENTRIES = ${body}
`
}

export async function fetchModelsDev(url = DEFAULT_URL, timeoutMs = FETCH_TIMEOUT_MS) {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), timeoutMs)
  try {
    const res = await fetch(url, { signal: controller.signal })
    if (!res.ok) throw new Error(`models.dev returned HTTP ${res.status}`)
    return await res.json()
  } finally {
    clearTimeout(timer)
  }
}

function argValue(argv, name) {
  const index = argv.indexOf(name)
  return index >= 0 ? argv[index + 1] : undefined
}

export async function main(argv = process.argv.slice(2)) {
  const input = argValue(argv, '--input')
  const out = argValue(argv, '--out') ?? DEFAULT_OUT
  const json = input ? JSON.parse(await readFile(resolve(input), 'utf8')) : await fetchModelsDev(argValue(argv, '--url'))
  const data = buildCatalogData(json)
  await writeFile(resolve(out), renderCatalogModule(data), 'utf8')
  return { generatedAt: data.generatedAt, entries: data.entries.length, out: resolve(out) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().then((result) => {
    console.log(`Wrote ${result.entries} price entries (${result.generatedAt}) to ${result.out}`)
  }).catch((error) => {
    console.error(`price generation failed: ${error?.message ?? error}`)
    process.exitCode = 1
  })
}
